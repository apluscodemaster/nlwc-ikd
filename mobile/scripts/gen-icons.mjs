#!/usr/bin/env node
/**
 * Regenerates src/components/icons.ts and rewrites icon imports to use it.
 *
 * Metro doesn't tree-shake, so `import { X } from "lucide-react-native"`
 * bundles all ~2,000 icons. This scans app/ and src/ for the icons actually
 * used, writes a module that deep-imports only those
 * (`lucide-react-native/icons/<file>`), and points every import at
 * `~/components/icons`. Run after using a new icon: `npm run icons`.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "components", "icons.ts");
const INDEX = join(ROOT, "node_modules", "lucide-react-native", "dist", "esm", "lucide-react-native.mjs");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return name === "node_modules" ? [] : walk(p);
    return /\.tsx?$/.test(name) ? [p] : [];
  });
}

// Export name → icon file, from lucide's own barrel (covers aliases).
const fileFor = new Map();
const indexSrc = readFileSync(INDEX, "utf8");
for (const m of indexSrc.matchAll(/export\s*\{([^}]*)\}\s*from\s*['"]\.\/icons\/([\w-]+)\.mjs['"]/g)) {
  for (const part of m[1].split(",")) {
    const alias = part.trim().match(/^default as (\w+)$/);
    if (alias) fileFor.set(alias[1], m[2]);
  }
}

const IMPORT_RE = /import\s*\{([^}]*)\}\s*from\s*["'](?:lucide-react-native|~\/components\/icons)["'];?/g;
const files = [...walk(join(ROOT, "app")), ...walk(join(ROOT, "src"))].filter((f) => f !== OUT);
const used = new Set();
for (const f of files) {
  for (const m of readFileSync(f, "utf8").matchAll(IMPORT_RE)) {
    for (const raw of m[1].split(",")) {
      const name = raw.trim();
      if (name && !name.startsWith("type ") && name !== "LucideIcon") used.add(name);
    }
  }
}

const missing = [...used].filter((n) => !fileFor.has(n));
if (missing.length) {
  console.error(`Unknown lucide icons: ${missing.join(", ")}`);
  process.exit(1);
}

const names = [...used].sort();
writeFileSync(
  OUT,
  [
    "// GENERATED by scripts/gen-icons.mjs: do not edit. Run `npm run icons` after using a new icon.",
    "// Deep imports keep the ~2,000 unused lucide icons out of the bundle (Metro doesn't tree-shake).",
    'export type { LucideIcon } from "lucide-react-native";',
    ...names.map((n) => `export { default as ${n} } from "lucide-react-native/icons/${fileFor.get(n)}";`),
    "",
  ].join("\n"),
);

// Point every icon import at the generated module (types included).
let rewritten = 0;
for (const f of files) {
  const src = readFileSync(f, "utf8");
  const next = src.replace(/from\s*["']lucide-react-native["']/g, 'from "~/components/icons"');
  if (next !== src) {
    writeFileSync(f, next);
    rewritten++;
  }
}
console.log(`icons.ts: ${names.length} icons; rewrote imports in ${rewritten} files.`);
