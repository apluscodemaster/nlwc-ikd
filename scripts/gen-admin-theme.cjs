// Generates src/app/admin/admin-theme.css (admin dark mode). Run: node scripts/gen-admin-theme.cjs
const fs = require("fs");
process.chdir(require("path").join(__dirname, ".."));

// Dark replacements for Tailwind's gray scale (light → dark, text stays readable).
const GRAY = {
  50: "#15181e",
  100: "#1b1f27",
  200: "#2a2f39",
  300: "#3a404c",
  400: "#8a91a0",
  500: "#a2a8b5",
  600: "#b8bdc8",
  700: "#cdd1d9",
  800: "#e1e4e9",
  900: "#f1f3f6",
  950: "#fafbfc",
};
const COLORS = [
  "red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan",
  "sky", "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose",
];
// Shades remapped for colours: pale fills become translucent tints of the 500;
// dark text shades become their lighter counterparts.
const tint = (c, pct) => `color-mix(in oklab, var(--color-${c}-500) ${pct}%, transparent)`;
const colourMap = (c) => ({
  50: tint(c, 12),
  100: tint(c, 20),
  200: tint(c, 32),
  600: `var(--color-${c}-400)`,
  700: `var(--color-${c}-300)`,
  800: `var(--color-${c}-300)`,
  900: `var(--color-${c}-200-orig)`,
});

const SURFACE = "#181b22"; // cards (bg-white)
const PAGE = "#0f1115";

// shadcn variables: dark values, keeping the brand orange.
const SHADCN_DARK = {
  "--background": PAGE,
  "--foreground": "#eceef2",
  "--card": SURFACE,
  "--card-foreground": "#eceef2",
  "--popover": SURFACE,
  "--popover-foreground": "#eceef2",
  "--secondary": "#232733",
  "--secondary-foreground": "#eceef2",
  "--muted": "#232733",
  "--muted-foreground": "#9aa1ae",
  "--border": "#2a2f39",
  "--input": "#2a2f39",
};
// Light values (copied from globals.css :root) for the [data-admin-light] reset.
const root = fs.readFileSync("src/app/globals.css", "utf8").replace(/\r\n/g, "\n");
const rootBlock = /:root\s*{([\s\S]*?)\n}/.exec(root)[1];
const SHADCN_LIGHT = {};
for (const k of Object.keys(SHADCN_DARK)) {
  const m = new RegExp(`${k}:\\s*([^;]+);`).exec(rootBlock);
  if (!m) throw new Error("no light value for " + k);
  SHADCN_LIGHT[k] = m[1].trim();
}

const overridden = [];
const darkVars = [];
for (const [shade, val] of Object.entries(GRAY)) {
  overridden.push(`--color-gray-${shade}`);
  darkVars.push(`  --color-gray-${shade}: ${val};`);
}
for (const c of COLORS) {
  for (const [shade, val] of Object.entries(colourMap(c))) {
    if (shade === "900") continue; // keep 900 as is
    overridden.push(`--color-${c}-${shade}`);
    darkVars.push(`  --color-${c}-${shade}: ${val};`);
  }
}

const origCapture = overridden.map((v) => `  --admin-orig${v.slice(1)}: var(${v});`).join("\n");
const lightReset = overridden.map((v) => `  ${v}: var(--admin-orig${v.slice(1)});`).join("\n");

const css = `/*
 * Admin dark mode (components/admin/AdminThemeToggle). GENERATED by
 * scripts/gen-admin-theme.cjs: edit that, not this file.
 *
 * Tailwind v4 colour utilities read CSS variables (bg-gray-50 is
 * var(--color-gray-50)), so remapping those variables re-colours every admin
 * page without dark: classes on each element. The remap is on <body> while
 * <html> has .admin-dark, which the toggle sets only inside /admin, so the
 * public site is never affected.
 *
 * Elements marked data-admin-light (e.g. pop-up previews) get the light
 * values back, so they show what visitors see.
 */

/* The original (light) values, captured on <html> before the remap. */
:root {
${origCapture}
}

html.admin-dark {
  color-scheme: dark;
}

html.admin-dark body {
${darkVars.join("\n")}
${Object.entries(SHADCN_DARK).map(([k, v]) => `  ${k}: ${v};`).join("\n")}
  background-color: ${PAGE};
  color: #eceef2;
}

/* White surfaces (text-white keeps --color-white, so these are per class). */
html.admin-dark body :where(.bg-white):not(:where([data-admin-light], [data-admin-light] *)) {
  background-color: ${SURFACE};
}
html.admin-dark body :where(.bg-white\\/95, .bg-white\\/90, .bg-white\\/80):not(:where([data-admin-light], [data-admin-light] *)) {
  background-color: color-mix(in oklab, ${SURFACE} 90%, transparent);
}
html.admin-dark body :where(.bg-white\\/50, .bg-white\\/60, .bg-white\\/70):not(:where([data-admin-light], [data-admin-light] *)) {
  background-color: color-mix(in oklab, ${SURFACE} 60%, transparent);
}
html.admin-dark body :where(.hover\\:bg-white:hover):not(:where([data-admin-light] *)) {
  background-color: #222632;
}
html.admin-dark body :where(.border-white, .ring-white):not(:where([data-admin-light] *)) {
  border-color: #2a2f39;
}
html.admin-dark body :where(.ring-black\\/5):not(:where([data-admin-light] *)) {
  --tw-ring-color: rgb(255 255 255 / 0.08);
}
/* White gradient stops (e.g. the login backdrop). */
html.admin-dark body :where(.from-white):not(:where([data-admin-light] *)) {
  --tw-gradient-from: ${SURFACE};
}
html.admin-dark body :where(.via-white):not(:where([data-admin-light] *)) {
  --tw-gradient-via: ${PAGE};
}
html.admin-dark body :where(.to-white):not(:where([data-admin-light] *)) {
  --tw-gradient-to: ${SURFACE};
}
html.admin-dark body :where(input, select, textarea)::placeholder {
  color: #6b7280;
}

/* Back to the public site's light look (previews). */
html.admin-dark body [data-admin-light] {
${lightReset}
${Object.entries(SHADCN_LIGHT).map(([k, v]) => `  ${k}: ${v};`).join("\n")}
  color-scheme: light;
  color: initial;
}
`;
fs.writeFileSync("src/app/admin/admin-theme.css", css);
console.log("ok", overridden.length, "variables");
